BEGIN;

CREATE TABLE IF NOT EXISTS ml_modelos (
    version UUID PRIMARY KEY,
    modulo TEXT NOT NULL CHECK (modulo IN ('demanda', 'anomalias', 'inasistencia')),
    modo TEXT NOT NULL CHECK (modo IN ('real', 'demo')),
    estado TEXT NOT NULL CHECK (estado IN ('insuficiente', 'evaluado', 'rechazado')),
    activo BOOLEAN NOT NULL DEFAULT FALSE,
    algoritmo TEXT,
    entorno JSONB NOT NULL,
    evaluacion JSONB NOT NULL,
    artefacto BYTEA,
    sha256 VARCHAR(64),
    firma VARCHAR(64),
    creado TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((artefacto IS NULL) = (sha256 IS NULL)),
    CHECK ((artefacto IS NULL) = (firma IS NULL)),
    CHECK (NOT activo OR (modo = 'real' AND estado = 'evaluado' AND artefacto IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ml_modelos_activo ON ml_modelos(modulo) WHERE activo;

CREATE TABLE IF NOT EXISTS ml_asistencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle_id INT NOT NULL REFERENCES detalle_permisos(id_d),
    actor_id INT NOT NULL REFERENCES trabajadores(id_t),
    resultado TEXT NOT NULL CHECK (resultado IN ('asistio', 'inasistencia', 'sin_verificar')),
    evidencia TEXT NOT NULL CHECK (length(btrim(evidencia)) >= 8),
    registrado TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ml_asistencias_detalle ON ml_asistencias(detalle_id, id DESC);

CREATE TABLE IF NOT EXISTS ml_predicciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version UUID NOT NULL REFERENCES ml_modelos(version),
    referencia TEXT NOT NULL,
    puntuacion DOUBLE PRECISION NOT NULL,
    hora TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(version, referencia)
);

CREATE TABLE IF NOT EXISTS ml_intentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INT NOT NULL REFERENCES users(id_u),
    permiso_id INT REFERENCES permisos(id_p),
    resultado TEXT NOT NULL,
    franja TEXT NOT NULL,
    ocurrido TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ml_intentos_fecha ON ml_intentos(ocurrido);

CREATE TABLE IF NOT EXISTS ml_incidentes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INT NOT NULL REFERENCES users(id_u),
    tipo TEXT NOT NULL CHECK (tipo IN ('anomalia', 'inasistencia', 'otro')),
    estado TEXT NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'confirmado', 'descartado', 'anulado', 'derivado')),
    referencia TEXT NOT NULL UNIQUE,
    alerta_id BIGINT UNIQUE REFERENCES ml_incidentes(id),
    asistencia_id BIGINT REFERENCES ml_asistencias(id),
    version UUID REFERENCES ml_modelos(version),
    evidencia JSONB NOT NULL,
    gravedad TEXT CHECK (gravedad IN ('ordinaria', 'grave')),
    ocurrido TIMESTAMPTZ NOT NULL,
    creado TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((tipo = 'anomalia') = (version IS NOT NULL)),
    CHECK (tipo <> 'inasistencia' OR asistencia_id IS NOT NULL),
    CHECK (alerta_id IS NULL OR (alerta_id <> id AND tipo <> 'anomalia'))
);
CREATE INDEX IF NOT EXISTS ml_incidentes_usuario ON ml_incidentes(usuario_id, estado, ocurrido);

CREATE TABLE IF NOT EXISTS ml_normas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo TEXT NOT NULL CHECK (tipo IN ('inasistencia', 'otro')),
    gravedad TEXT NOT NULL CHECK (gravedad IN ('ordinaria', 'grave')),
    medida TEXT NOT NULL CHECK (medida IN ('preventiva', 'advertencia', 'suspension')),
    minimo_previas INT NOT NULL CHECK (minimo_previas >= 0),
    maximo_horas INT CHECK (maximo_horas > 0),
    fundamento TEXT NOT NULL,
    criterio TEXT NOT NULL,
    aprobacion TEXT,
    autor_id INT NOT NULL REFERENCES trabajadores(id_t),
    aprobador_id INT REFERENCES trabajadores(id_t),
    aprobada TIMESTAMPTZ,
    vigente BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK ((medida = 'advertencia') = (maximo_horas IS NULL)),
    CHECK (NOT vigente OR (aprobacion IS NOT NULL AND aprobada IS NOT NULL AND aprobador_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ml_normas_vigente
    ON ml_normas(tipo, gravedad, (medida = 'preventiva'), minimo_previas) WHERE vigente;

CREATE TABLE IF NOT EXISTS ml_medidas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidente_id BIGINT NOT NULL REFERENCES ml_incidentes(id),
    norma_id BIGINT NOT NULL REFERENCES ml_normas(id),
    actor_id INT NOT NULL REFERENCES trabajadores(id_t),
    tipo TEXT NOT NULL CHECK (tipo IN ('preventiva', 'advertencia', 'suspension')),
    estado TEXT NOT NULL CHECK (estado IN ('confirmada', 'levantada', 'anulada')),
    motivo TEXT NOT NULL,
    inicio TIMESTAMPTZ NOT NULL DEFAULT now(),
    fin TIMESTAMPTZ,
    CHECK ((tipo = 'advertencia') = (fin IS NULL)),
    CHECK (fin IS NULL OR fin > inicio)
);
CREATE UNIQUE INDEX IF NOT EXISTS ml_medidas_sancion ON ml_medidas(incidente_id)
    WHERE tipo <> 'preventiva' AND estado <> 'anulada';
CREATE INDEX IF NOT EXISTS ml_medidas_incidente ON ml_medidas(incidente_id);

CREATE TABLE IF NOT EXISTS ml_descargos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medida_id BIGINT NOT NULL REFERENCES ml_medidas(id),
    usuario_id INT NOT NULL REFERENCES users(id_u),
    texto TEXT NOT NULL,
    creado TIMESTAMPTZ NOT NULL DEFAULT now(),
    decision TEXT,
    revisor_id INT REFERENCES trabajadores(id_t),
    revisado TIMESTAMPTZ,
    CHECK ((decision IS NULL AND revisor_id IS NULL AND revisado IS NULL)
        OR (decision IS NOT NULL AND revisor_id IS NOT NULL AND revisado IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ml_descargos_pendiente ON ml_descargos(medida_id) WHERE revisado IS NULL;

CREATE TABLE IF NOT EXISTS ml_decisiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidente_id BIGINT REFERENCES ml_incidentes(id),
    norma_id BIGINT REFERENCES ml_normas(id),
    actor_id INT NOT NULL REFERENCES trabajadores(id_t),
    accion TEXT NOT NULL,
    motivo TEXT NOT NULL,
    datos JSONB NOT NULL DEFAULT '{}'::jsonb,
    creado TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(incidente_id, norma_id) = 1)
);
CREATE INDEX IF NOT EXISTS ml_decisiones_incidente ON ml_decisiones(incidente_id, creado);

COMMIT;

